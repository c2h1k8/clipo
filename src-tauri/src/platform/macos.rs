/// 範囲選択スクショをファイルに保存（キャンセルされたら false）
pub fn capture_region_to_file(out: &Path) -> bool {
    let _ = std::fs::remove_file(out);
    let _ = std::process::Command::new("screencapture")
        .args(["-i", "-x"])
        .arg(out)
        .status();
    out.exists()
}

/// Vision で画像から文字を読み取る（日本語・英語）
pub fn ocr_png(png: &[u8]) -> Result<String, String> {
    use objc2::AllocAnyThread;
    use objc2_foundation::{NSArray, NSData, NSDictionary};
    use objc2_vision::{VNImageRequestHandler, VNRecognizeTextRequest, VNRequest, VNRequestTextRecognitionLevel};

    unsafe {
        let data = NSData::with_bytes(png);
        let handler =
            VNImageRequestHandler::initWithData_options(VNImageRequestHandler::alloc(), &data, &NSDictionary::new());
        let req = VNRecognizeTextRequest::new();
        req.setRecognitionLevel(VNRequestTextRecognitionLevel::Accurate);
        req.setUsesLanguageCorrection(true);
        let langs = NSArray::from_retained_slice(&[NSString::from_str("ja-JP"), NSString::from_str("en-US")]);
        req.setRecognitionLanguages(&langs);
        let as_req: &VNRequest = &req;
        handler
            .performRequests_error(&NSArray::from_slice(&[as_req]))
            .map_err(|e| e.localizedDescription().to_string())?;

        let Some(results) = req.results() else { return Ok(String::new()) };
        // 上から下、左から右の順に並べる（Vision の座標は左下原点）
        let mut lines: Vec<(f64, f64, String)> = results
            .iter()
            .filter_map(|obs| {
                let cand = obs.topCandidates(1);
                let text = cand.firstObject()?.string().to_string();
                let b = obs.boundingBox();
                Some((b.origin.y + b.size.height, b.origin.x, text))
            })
            .collect();
        lines.sort_by(|a, b| b.0.partial_cmp(&a.0).unwrap().then(a.1.partial_cmp(&b.1).unwrap()));
        Ok(lines.into_iter().map(|l| l.2).collect::<Vec<_>>().join("\n"))
    }
}

/// 範囲選択して文字起こし。キャンセルなら None
pub fn capture_and_ocr(tmp: &Path) -> Result<Option<String>, String> {
    if !capture_region_to_file(tmp) {
        return Ok(None);
    }
    let png = std::fs::read(tmp).map_err(|e| e.to_string())?;
    let _ = std::fs::remove_file(tmp);
    ocr_png(&png).map(Some)
}

pub fn ocr_image_file(path: &Path) -> Result<String, String> {
    ocr_png(&std::fs::read(path).map_err(|e| e.to_string())?)
}

