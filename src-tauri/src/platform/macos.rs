/// アプリアイコンを PNG として保存（64pt 相当のサイズを OS に選ばせる）
pub fn save_app_icon(app: &AppInfo, out: &Path) -> bool {
    use objc2::AllocAnyThread;
    use objc2_app_kit::{NSBitmapImageFileType, NSBitmapImageRep};
    use objc2_foundation::{NSDictionary, NSPoint, NSRect, NSSize};

    let Some(path) = &app.path else { return false };
    let png = unsafe {
        let img = NSWorkspace::sharedWorkspace().iconForFile(&NSString::from_str(path));
        let mut rect = NSRect::new(NSPoint::new(0.0, 0.0), NSSize::new(64.0, 64.0));
        let Some(cg) = img.CGImageForProposedRect_context_hints(&mut rect, None, None) else {
            return false;
        };
        let rep = NSBitmapImageRep::initWithCGImage(NSBitmapImageRep::alloc(), &cg);
        match rep.representationUsingType_properties(NSBitmapImageFileType::PNG, &NSDictionary::new()) {
            Some(d) => d.to_vec(),
            None => return false,
        }
    };
    std::fs::write(out, png).is_ok()
}

/// OS標準の範囲選択スクショを起動し、終わるまで待つ（結果はクリップボードへ）
pub fn run_screenshot() {
    let _ = std::process::Command::new("screencapture")
        .args(["-i", "-c"])
        .status();
}

