static TARGET_PID: AtomicI32 = AtomicI32::new(0);

pub fn change_count() -> i64 {
    unsafe { NSPasteboard::generalPasteboard().changeCount() as i64 }
}

/// パスワード管理アプリなどが「記録しないで」と印を付けたコピーか
/// (http://nspasteboard.org の慣習)
pub fn is_concealed() -> bool {
    unsafe {
        let pb = NSPasteboard::generalPasteboard();
        let Some(types) = pb.types() else { return false };
        types.iter().any(|t| {
            let s = t.to_string();
            s == "org.nspasteboard.ConcealedType"
                || s == "org.nspasteboard.TransientType"
                || s == "org.nspasteboard.AutoGeneratedType"
                || s == "com.agilebits.onepassword"
        })
    }
}

fn frontmost() -> Option<AppInfo> {
    unsafe {
        let app = NSWorkspace::sharedWorkspace().frontmostApplication()?;
        let id = app.bundleIdentifier().map(|s| s.to_string())?;
        let name = app
            .localizedName()
            .map(|s| s.to_string())
            .unwrap_or_else(|| id.clone());
        let path = app.bundleURL().and_then(|u| u.path()).map(|p| p.to_string());
        Some(AppInfo { id, name, path, pid: app.processIdentifier() as u32 })
    }
}

/// コピーされた瞬間のコピー元アプリの推定（前面アプリ）
pub fn source_app() -> Option<AppInfo> {
    frontmost()
}

/// OS標準のスクショ（Cmd+Ctrl+Shift+4 など）の撮影UIが動いているか
pub fn screenshot_ui_running() -> bool {
    unsafe {
        let id = NSString::from_str("com.apple.screencaptureui");
        NSRunningApplication::runningApplicationsWithBundleIdentifier(&id).count() > 0
    }
}

/// パネルを出す直前の前面アプリを覚えておく
pub fn remember_target() {
    if let Some(app) = frontmost() {
        if app.pid != std::process::id() {
            TARGET_PID.store(app.pid as i32, Ordering::SeqCst);
        }
    }
}

/// 覚えておいたアプリを前面に戻す
pub fn activate_target() {
    let pid = TARGET_PID.load(Ordering::SeqCst);
    if pid == 0 {
        return;
    }
    unsafe {
        if let Some(app) = NSRunningApplication::runningApplicationWithProcessIdentifier(pid) {
            #[allow(deprecated)]
            app.activateWithOptions(NSApplicationActivationOptions::ActivateIgnoringOtherApps);
        }
    }
}

