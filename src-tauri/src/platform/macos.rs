fn screencapture_pref(key: &str) -> Option<String> {
    let out = std::process::Command::new("defaults")
        .args(["read", "com.apple.screencapture", key])
        .output()
        .ok()?;
    let v = String::from_utf8_lossy(&out.stdout).trim().to_string();
    (out.status.success() && !v.is_empty()).then_some(v)
}

/// OS 標準スクショ（⌘⇧3/4/5）の保存先フォルダ
pub fn screenshot_dir() -> Option<std::path::PathBuf> {
    let home = std::env::var("HOME").ok()?;
    let dir = match screencapture_pref("location") {
        Some(p) if p.starts_with("~/") => std::path::PathBuf::from(&home).join(&p[2..]),
        Some(p) => std::path::PathBuf::from(p),
        None => std::path::PathBuf::from(&home).join("Desktop"),
    };
    dir.is_dir().then_some(dir)
}

/// スクショのファイル名の先頭（OS の言語ごと＋ユーザー設定）
pub fn screenshot_prefixes() -> Vec<String> {
    let mut v: Vec<String> = [
        "スクリーンショット", "Screenshot", "Screen Shot", "Bildschirmfoto",
        "Capture d’écran", "Captura de pantalla", "截屏", "스크린샷",
    ]
    .iter()
    .map(|s| s.to_string())
    .collect();
    if let Some(name) = screencapture_pref("name") {
        v.push(name);
    }
    v
}

